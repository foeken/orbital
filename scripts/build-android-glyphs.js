'use strict';
// The Android app's glyphs (android/shared/.../ui/GlyphData.kt): the Nucleo line icons of icons.js, the ones the desktop
// and the iPhone app draw (scripts/build-ios-glyphs.js), as path data Compose builds ImageVectors from (ui/Glyphs.kt),
// tinted like Material icons. Only the names the app uses; add one here when a screen needs it.
// Run: node scripts/build-android-glyphs.js
const fs = require('node:fs');
const path = require('node:path');

const USED = ['timeline', 'library', 'info', 'chatgpt', 'license', 'task', 'doc', 'space', 'member', 'discuss', 'tlAccepted', 'tlLater', 'tlInbox', 'tlNew', 'updated', 'robot', 'tana', 'calendar', 'free', 'todayTasks', 'search', 'language', 'pinRoute', 'hidden', 'lock', 'userLock', 'houseLock', 'users', 'brain', 'sparkle', 'pin', 'inbox', 'trash', 'image'];
// as the iPhone's: the check in finished work's green disc heavier, and the side menu's glyphs weighted like its medium text
const HEAVY = { applyDone: ['apply', 2.5], timelineMenu: ['timeline', 1.6], searchMenu: ['search', 1.6] };

const window = {};
new Function('window', fs.readFileSync(path.join(__dirname, '..', 'icons.js'), 'utf8'))(window);

const num = (s) => Number(s);
const attrsOf = (s) => Object.fromEntries([...s.matchAll(/([\w-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]));
const width = (v) => { const m = /^var\(--[\w-]+, ([\d.]+)\)$/.exec(v || ''); return m ? num(m[1]) : num(v); };
const pts = (s) => s.trim().split(/[\s,]+/).map(num);
// every shape as path data, so Compose has one kind of part to draw
function d(tag, a) {
  switch (tag) {
    case 'path': return a.d;
    case 'line': return 'M' + a.x1 + ' ' + a.y1 + 'L' + a.x2 + ' ' + a.y2;
    case 'polyline': case 'polygon': {
      const p = pts(a.points), out = [];
      for (let i = 0; i < p.length; i += 2) out.push((i ? 'L' : 'M') + p[i] + ' ' + p[i + 1]);
      return out.join('') + (tag === 'polygon' ? 'Z' : '');
    }
    case 'circle': { const cx = num(a.cx), cy = num(a.cy), r = num(a.r); return 'M' + (cx - r) + ' ' + cy + 'A' + r + ' ' + r + ' 0 1 0 ' + (cx + r) + ' ' + cy + 'A' + r + ' ' + r + ' 0 1 0 ' + (cx - r) + ' ' + cy + 'Z'; }
    case 'rect': {
      const x = num(a.x || 0), y = num(a.y || 0), w = num(a.width), h = num(a.height);
      let rx = num(a.rx ?? a.ry ?? 0), ry = num(a.ry ?? a.rx ?? 0);
      rx = Math.min(rx, w / 2); ry = Math.min(ry, h / 2);
      if (!rx || !ry) return 'M' + x + ' ' + y + 'H' + (x + w) + 'V' + (y + h) + 'H' + x + 'Z';
      const arc = (ex, ey) => 'A' + rx + ' ' + ry + ' 0 0 1 ' + ex + ' ' + ey;
      return 'M' + (x + rx) + ' ' + y + 'H' + (x + w - rx) + arc(x + w, y + ry) + 'V' + (y + h - ry) + arc(x + w - rx, y + h) + 'H' + (x + rx) + arc(x, y + h - ry) + 'V' + (y + ry) + arc(x + rx, y) + 'Z';
    }
    default: throw new Error('no path for <' + tag + '>');
  }
}

function parts(svg, name, heavy) {
  const view = pts(/viewBox="([^"]+)"/.exec(svg)[1]), out = [], stack = [];
  for (const m of svg.matchAll(/<(\/?)(\w+)([^>]*?)(\/?)>/g)) {
    const [, close, tag, rest, selfClose] = m;
    if (close) { if (tag === 'g' || tag === 'svg') stack.pop(); continue; }
    const a = attrsOf(rest), inherited = Object.assign({}, ...stack);
    if (a.transform && a.transform !== 'translate(0 0)') throw new Error(name + ': transform ' + a.transform);
    if (tag === 'g' || tag === 'svg') { if (!selfClose) stack.push(Object.fromEntries(Object.entries(a).filter(([k]) => /^(fill|stroke|stroke-width|stroke-linecap|stroke-linejoin)$/.test(k)))); continue; }
    const s = { ...inherited, ...a };
    const fill = (s.fill ?? 'currentColor') !== 'none', stroke = (s.stroke ?? 'none') !== 'none';
    const w = heavy ?? width(s['stroke-width'] ?? '1');
    if (!fill && (!stroke || !w)) continue;
    out.push({ d: d(tag, a), fill, stroke: stroke ? w : 0, cap: s['stroke-linecap'] || 'butt', join: s['stroke-linejoin'] || 'miter' });
  }
  return { view, out };
}

const kt = (name, svg, heavy) => {
  const { view, out } = parts(svg, name, heavy);
  const list = out.map((p) => '        P("' + p.d.replace(/\s+/g, ' ') + '", ' + p.fill + ', ' + p.stroke + 'f, ' + JSON.stringify(p.cap) + ', ' + JSON.stringify(p.join) + '),').join('\n');
  return '    "' + name + '" to G(' + view.map((v) => v + 'f').join(', ') + ', listOf(\n' + list + '\n    )),';
};

const entries = [];
for (const name of USED) {
  if (!window.ICONS[name]) throw new Error('no glyph ' + name + ' in icons.js');
  entries.push(kt(name, window.ICONS[name]));
}
for (const [name, [from, w]] of Object.entries(HEAVY)) entries.push(kt(name, window.ICONS[from], w));

const file = path.join(__dirname, '..', 'android', 'shared', 'src', 'commonMain', 'kotlin', 'com', 'dreetje', 'orbital', 'ui', 'GlyphData.kt');
fs.mkdirSync(path.dirname(file), { recursive: true });
fs.writeFileSync(file, '// Generated by scripts/build-android-glyphs.js from icons.js. Do not edit; run it again.\npackage com.dreetje.orbital.ui\n\n' +
  '// a glyph: its viewBox, then each part as path data, filled or stroked (its width, cap and join)\ninternal class P(val d: String, val fill: Boolean, val stroke: Float, val cap: String, val join: String)\n' +
  'internal class G(val x: Float, val y: Float, val w: Float, val h: Float, val parts: List<P>)\n\n' +
  'internal val GLYPHS: Map<String, G> = mapOf(\n' + entries.join('\n') + '\n)\n');
console.log('wrote', entries.length, 'glyphs to', path.relative(process.cwd(), file));

