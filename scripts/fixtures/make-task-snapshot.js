'use strict';
// Rebuilds task-snapshot.b64: a synthetic task document with the same shape a real one has (a link mark, a
// heading, an inline mention), so the offline checks exercise the real accessors without carrying anyone's
// actual Tana content. Run: node scripts/fixtures/make-task-snapshot.js
const fs = require('node:fs');
const path = require('node:path');
const { LoroMap, LoroList, LoroText } = require('loro-crdt');
const { Document } = require('../../sdk/document');
const { initDocument } = require('../../sdk/node');

// Kept in step with the constants at the top of scripts/sdk-check.js.
const DOC = 'tana:text:01exampleh0000000000000000';
const ME = 'tana:user-profile:01examplei0000000000000000';
const MENTIONED = 'tana:text:01examplet0000000000000000';
const MARKS = Object.fromEntries(['bold', 'italic', 'strike', 'code', 'link'].map((m) => [m, { expand: 'none' }]));

const doc = new Document(DOC, { peerId: '1' });
doc.transact((l) => {
  initDocument(l, 'Review the sample agreement', ME, { kind: 'task', now: 1788262342702 });
  l.getMap('data').set('titleAutoGenerated', true); // Tana sets this on an auto-titled task; setTitle removes it again
  l.configTextStyle(MARKS); // marks must be configured before they are written, or expand behaviour is wrong
  const children = l.getMap('content').get('children');
  while (children.length) children.delete(0, 1); // drop initDocument's empty seed paragraph
  const block = (nodeName, blockId, level) => {
    const b = children.pushContainer(new LoroMap());
    b.set('nodeName', nodeName);
    const attributes = b.setContainer('attributes', new LoroMap());
    attributes.set('blockId', blockId);
    if (level) attributes.set('level', level);
    return b.setContainer('children', new LoroList());
  };

  const first = block('paragraph', '6s8vb70s').pushContainer(new LoroText());
  first.insert(0, 'Imported from Tana Outliner on 2026-09-09.\nOutliner ID: EXAMPLE12345');
  first.mark({ start: 'Imported from '.length, end: 'Imported from Tana Outliner'.length }, 'link', 'tana:EXAMPLE12345');

  block('heading', 'dv8c4sp7', 2).pushContainer(new LoroText()).insert(0, 'Research context — 10 September 2026');

  const third = block('paragraph', 'r4hz3a0b');
  third.pushContainer(new LoroText()).insert(0, 'The ');
  const mention = third.pushContainer(new LoroMap());
  mention.set('nodeName', 'mention');
  const attributes = mention.setContainer('attributes', new LoroMap());
  attributes.set('label', 'sample agreement review');
  attributes.set('tanaUri', MENTIONED);
  third.pushContainer(new LoroText()).insert(0, ' names a reviewer and a deadline.');
});

const out = path.join(__dirname, 'task-snapshot.b64');
fs.writeFileSync(out, Buffer.from(doc.loro.export({ mode: 'snapshot' })).toString('base64') + '\n');
console.log('wrote', out, fs.statSync(out).size, 'bytes');
